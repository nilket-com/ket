-- PRODUCT-0130's temporal-axis exhibit: calendar ticks are a distinct
-- capability from numeric tick_step, so the source is a real DATE column.
DROP TABLE IF EXISTS temporal_tick_intervals;

CREATE TABLE temporal_tick_intervals (
	calendar_date DATE NOT NULL,
	elapsed_at TIMESTAMPTZ NOT NULL,
	calendar_at TIMESTAMPTZ NOT NULL,
	monthly_active FLOAT64 NOT NULL,
	hourly_active FLOAT64 NOT NULL
);

