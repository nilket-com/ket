#[test]
fn historical_validation_and_terminals() {
	let reserve = command("reserve");
	let id = id_of(&reserve);
	// Permission at 6, an unrelated entry at 7, the reservation at 8.
	let s = step(
		&permitted(),
		&cover(7),
		7,
		0,
		&ApplyResult2::Covered,
		&[(k1(), 6, None)],
		&[],
	);
	let r8 = step(
		&s,
		&reserve,
		8,
		0,
		&reserved(&reserve, 8),
		&[(k1(), 6, None)],
		&[(id, 8)],
	);
	let base = root_of(&r8).state;
	validate_state(&base).unwrap();
	let k = k1();
	let old = *base.permissions.get(&k).unwrap();
	// Corruptions keep the cached accounting and non-grant summary coherent with the edited records
	// (validate_state does not read the cached summary, so this states the setup, not the reason
	// for rejection).
	let coherent = |s: &mut State2, after: Option<PermissionRecord2>| {
		s.derived.usage = usage(s).unwrap();
		for i in [Some(old.enrolled), old.revoked].into_iter().flatten() {
			s.derived.non_grants.remove(&i.index);
		}
		if let Some(p) = after {
			for i in [Some(p.enrolled), p.revoked].into_iter().flatten() {
				s.derived.non_grants.insert(i.index, ());
			}
		}
	};
	let with = |f: &dyn Fn(&mut PermissionRecord2), covered: u64| {
		let mut s = base.clone();
		let mut p = old;
		f(&mut p);
		s.permissions.insert(k, p);
		s.covered = l(covered);
		coherent(&mut s, Some(p));
		s
	};
	// Missing permission.
	let mut missing = base.clone();
	missing.permissions = Map::new();
	coherent(&mut missing, None);
	assert_eq!(
		missing.derived.usage.registry,
		base.derived.usage.registry - 117
	);
	assert_eq!(
		validate_state(&missing).err(),
		Some(RootError2::RootInvariant)
	);
	// Enrolled after the reservation (at a free coordinate).
	assert_eq!(
		validate_state(&with(&|p| p.enrolled = l(9), 9)).err(),
		Some(RootError2::RootInvariant)
	);
	// Revoked before the reservation (at the free coordinate 7).
	assert_eq!(
		validate_state(&with(&|p| p.revoked = Some(l(7)), 8)).err(),
		Some(RootError2::RootInvariant)
	);
	// Revoked after the reservation: the control is valid, and its edited summary equals a rebuild.
	let control = with(&|p| p.revoked = Some(l(9)), 9);
	validate_state(&control).unwrap();
	assert!(control.derived == Derived2::build(&control).unwrap());
	// The helper's own boundaries; full validation rejects these equalities by coordinate collision.
	let c = claim_of(&reserve);
	assert_eq!(
		admission_permission(&base, &c, 6).unwrap(),
		Some((18, None))
	);
	assert_eq!(
		admission_permission(&with(&|p| p.revoked = Some(l(8)), 8), &c, 8).unwrap(),
		Some((19, Some(l(8))))
	);
	assert_eq!(
		validate_state(&with(&|p| p.revoked = Some(l(8)), 8)).err(),
		Some(RootError2::RootInvariant)
	);
	// Terminals: a later permission revocation creates no trigger and Finalize is accepted.
	let revoked = [(k1(), 6, Some(9))];
	let t = step(
		&r8,
		&revoke_statement(),
		9,
		0,
		&permission(k1(), 3, 6, Some(9)),
		&revoked,
		&[(id, 8)],
	);
	let rt = root_of(&t);
	let stored = rt.state.parents.get(&id).unwrap();
	assert_eq!(trigger(&rt.state, stored).unwrap(), None);
	let mut a = attestation();
	a.grant = c.original.reference().unwrap();
	a.reservation = l(8);
	a.claim_digest = c.digest().unwrap();
	a.authority = c.authority;
	let finalize = Command2::Finalize {
		identity: c.manifest.identity,
		digest: c.digest().unwrap(),
		reservation: l(8),
		attestation: a.clone(),
	};
	let a_bytes = a.encode().unwrap();
	let held = c.held_bytes().unwrap();
	let parent = |terminal: Terminal2, new_effect: bool| ApplyResult2::Parent {
		record: ParentRecord2 {
			claim: c.clone(),
			reservation: l(8),
			held_bytes: held,
			terminal: Some(terminal),
		},
		new_effect,
	};
	let accepted = Terminal2::Accepted {
		first: l(10),
		evidence: hash(b"VISROOT2-EVIDENCE\0", &a_bytes),
	};
	let done = step(
		&t,
		&finalize,
		10,
		1,
		&parent(accepted, true),
		&revoked,
		&[(id, 8)],
	);
	let stored = root_of(&done).state.parents.get(&id).unwrap().record();
	assert!(stored.terminal == Some(accepted) && stored.held_bytes == held);
	// A later authority revocation still triggers cause 4, and the actual terminal is Refused.
	let x = step(
		&t,
		&Command2::RevokeAuthority(c.authority),
		10,
		0,
		&registered(10),
		&revoked,
		&[(id, 8)],
	);
	let rx = root_of(&x);
	assert_eq!(
		trigger(&rx.state, rx.state.parents.get(&id).unwrap()).unwrap(),
		Some((4, l(10)))
	);
	let resolve = Command2::Resolve {
		identity: c.manifest.identity,
		digest: c.digest().unwrap(),
		reservation: l(8),
		cause: 4,
		anchor: l(10),
	};
	let refused = Terminal2::Refused {
		first: l(11),
		cause: 4,
		anchor: l(10),
	};
	let closed = step(
		&x,
		&resolve,
		11,
		0,
		&parent(refused, false),
		&revoked,
		&[(id, 8)],
	);
	assert!(
		root_of(&closed)
			.state
			.parents
			.get(&id)
			.unwrap()
			.record()
			.terminal == Some(refused)
	);
}

#[test]
fn denied_eighteen_and_nineteen_codec() {
	let (g, c) = gc();
	for (name, processed, reason, reference) in
		[("eighteen", 7, 18, None), ("nineteen", 8, 19, Some(7))]
	{
		let b = unhex(rv()["denied"][name].as_str().unwrap());
		let (dg, dc, dl, r) = ApplyResult2::decode(&b).unwrap();
		assert!((dg, dc, dl) == (g, c, l(processed)) && r == denied(reason, reference));
		assert_eq!(r.encode(g, c, l(processed)).unwrap(), b);
	}
	for (name, value) in rv()["denied_refusals"].as_object().unwrap() {
		let b = unhex(value.as_str().unwrap());
		if name == "twenty" {
			let (dg, dc, dl, result) = ApplyResult2::decode(&b).unwrap();
			assert_eq!(result, denied(20, None));
			assert_eq!(result.encode(dg, dc, dl).unwrap(), b);
		} else {
			assert_eq!(
				ApplyResult2::decode(&b).err(),
				Some(RootError2::Codec),
				"{name}"
			);
		}
	}
	for reason in [23, 24] {
		let result = denied(reason, None);
		let bytes = result.encode(g, c, l(8)).unwrap();
		assert_eq!(ApplyResult2::decode(&bytes).unwrap().3, result);
		assert_eq!(
			denied(reason, Some(6)).encode(g, c, l(8)).err(),
			Some(RootError2::Codec)
		);
		let reference_bytes = denied(17, Some(6)).encode(g, c, l(8)).unwrap();
		let mut body = open(&reference_bytes, b"VISRES02", COMMAND_BYTES2)
			.unwrap()
			.to_vec();
		assert_eq!(body[52], 6);
		body[53..55].copy_from_slice(&reason.to_le_bytes());
		let raw = envelope(b"VISRES02", &body, COMMAND_BYTES2).unwrap();
		assert_eq!(ApplyResult2::decode(&raw).err(), Some(RootError2::Codec));
	}
	let valid = denied(24, None).encode(g, c, l(8)).unwrap();
	let mut body = open(&valid, b"VISRES02", COMMAND_BYTES2).unwrap().to_vec();
	body[53..55].copy_from_slice(&25u16.to_le_bytes());
	assert_eq!(
		ApplyResult2::decode(&envelope(b"VISRES02", &body, COMMAND_BYTES2).unwrap()).err(),
		Some(RootError2::Codec)
	);
	for reason in 1..=25 {
		let result = denied(reason, None).encode(g, c, l(8));
		assert_eq!(
			result.is_ok(),
			matches!(reason, 1..=18 | 20..=24),
			"{reason}"
		);
	}
	for bad in [
		denied(18, Some(6)),
		denied(19, None),
		denied(25, None),
		denied(23, Some(6)),
		denied(24, Some(6)),
		denied(20, Some(6)),
		denied(21, Some(6)),
		denied(22, Some(6)),
	] {
		assert_eq!(bad.encode(g, c, l(8)).err(), Some(RootError2::Codec));
	}
	assert_eq!(
		denied(19, Some(9)).encode(g, c, l(8)).err(),
		Some(RootError2::Codec)
	);
	assert!(denied(19, Some(8)).encode(g, c, l(8)).is_ok());
	assert!(
		denied(17, Some(9)).encode(g, c, l(8)).is_ok(),
		"old reasons keep their permissive reference"
	);
}

#[test]
fn legacy_ungoverned_reserve_is_unchanged() {
	// Every committed root golden is ungoverned and has no requirement.
	let goldens: serde_json::Value = serde_json::from_str(include_str!("goldens.json")).unwrap();
	for item in goldens["fixtures"].as_array().unwrap() {
		let name = item["name"].as_str().unwrap();
		if !name.starts_with("root_") {
			continue;
		}
		let r = root(name);
		assert_ne!(r.state.control_len, 137, "{name}");
		for p in r.state.parents.values() {
			assert_eq!(
				admission_permission(&r.state, &p.claim, p.reservation.index).unwrap(),
				None
			);
		}
		assert_eq!(
			admission_permission(&r.state, &claim(), r.covered().index + 1).unwrap(),
			None
		);
	}
	// A genuinely new Reserve on an ungoverned root takes the whole Reserve path, permission step
	// included, and still byte-matches the frozen oracle (through `next`).
	let r = root("root_reserved");
	let mut c = claim();
	c.manifest.identity.sequence += 1;
	let (n, o) = next(&r, &Command2::Reserve(c), &[], 1);
	assert!(
		matches!(o, ApplyResult2::Parent { .. }),
		"reserved without any permission"
	);
	assert_eq!(n.state.parents.len(), 2);
	assert_eq!(n.state.permissions.len(), 0);
}
